#!/usr/bin/env python3
"""Copy the unexpected-read alarm rule from the CloudFormation stack into the
local AWS mock, so the laptop simulation uses the exact rule AWS runs.

    scripts/sync-event-pattern.py           # write dev/aws-mock/rules/secret-read-alert.json
    scripts/sync-event-pattern.py --check   # fail if that file is stale (CI)

It reads SecretReadAlertRule from infra/cloudformation.yaml: the EventPattern,
the State (EventBridge only delivers read-only CloudTrail events, such as
GetSecretValue, to rules in state ENABLED_WITH_ALL_CLOUDTRAIL_MANAGEMENT_EVENTS)
and the target's InputTransformer. CloudFormation functions are kept in their
JSON form ({"Ref": ...}, {"Fn::GetAtt": ...}, {"Fn::Sub": ...}); the mock binds
them to local values and refuses to start if one is unknown.
"""
import hashlib
import json
import pathlib
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
TEMPLATE = ROOT / "infra" / "cloudformation.yaml"
OUT = ROOT / "dev" / "aws-mock" / "rules" / "secret-read-alert.json"
RULE = "SecretReadAlertRule"


class CfnLoader(yaml.SafeLoader):
    pass


def _intrinsic(name):
    def construct(loader, node):
        if isinstance(node, yaml.ScalarNode):
            value = loader.construct_scalar(node)
            if name == "Fn::GetAtt":
                return {name: value}
        elif isinstance(node, yaml.SequenceNode):
            value = loader.construct_sequence(node, deep=True)
        else:
            value = loader.construct_mapping(node, deep=True)
        return {name: value}

    return construct


for tag, name in {
    "!Ref": "Ref", "!GetAtt": "Fn::GetAtt", "!Sub": "Fn::Sub", "!If": "Fn::If", "!Join": "Fn::Join",
    "!Select": "Fn::Select", "!Split": "Fn::Split", "!Equals": "Fn::Equals", "!Not": "Fn::Not",
    "!And": "Fn::And", "!Or": "Fn::Or", "!FindInMap": "Fn::FindInMap", "!ImportValue": "Fn::ImportValue",
    "!GetAZs": "Fn::GetAZs", "!Base64": "Fn::Base64", "!Cidr": "Fn::Cidr", "!Condition": "Condition",
}.items():
    CfnLoader.add_constructor(tag, _intrinsic(name))

ALLOWED = {"Ref", "Fn::GetAtt", "Fn::Sub"}


def check_intrinsics(node, where="EventPattern"):
    if isinstance(node, dict):
        fns = [k for k in node if k.startswith("Fn::") or k == "Ref"]
        if fns and fns[0] not in ALLOWED:
            sys.exit(f"{where}: {fns[0]} can't be bound by the local mock; use Ref, GetAtt or Sub")
        for k, v in node.items():
            check_intrinsics(v, f"{where}.{k}")
    elif isinstance(node, list):
        for i, v in enumerate(node):
            check_intrinsics(v, f"{where}[{i}]")


def extract():
    doc = yaml.load(TEMPLATE.read_text(), Loader=CfnLoader)
    rule = doc["Resources"][RULE]["Properties"]
    target = rule["Targets"][0]
    body = {
        "eventPattern": rule["EventPattern"],
        "state": rule.get("State", "ENABLED"),
        "target": {"arn": target["Arn"], "inputTransformer": target.get("InputTransformer")},
    }
    check_intrinsics(body)
    digest = hashlib.sha256(json.dumps(body, sort_keys=True).encode()).hexdigest()
    return {
        "comment": f"Generated by scripts/sync-event-pattern.py from {TEMPLATE.relative_to(ROOT)} ({RULE}). Do not edit.",
        "sha256": digest,
        **body,
    }


def main():
    text = json.dumps(extract(), indent=2) + "\n"
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit(f"{OUT.relative_to(ROOT)} is stale: run scripts/sync-event-pattern.py")
        print(f"{OUT.relative_to(ROOT)} matches {RULE} in the template")
        return
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()

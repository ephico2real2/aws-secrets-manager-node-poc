#!/usr/bin/env node
// Generate the alert rules from backend/src/alerts/catalogue.js, so the local
// rules, the AWS alarms and the docs can't disagree:
//
//   deploy/observability/vmalert-rules.yaml          vmalert, LogsQL on VictoriaLogs (local)
//   deploy/observability/alertmanager.yml (block)    routing and re-notify intervals (local)
//   infra/cloudformation.yaml (marked block)         CloudWatch Logs metric filters + alarms (AWS)
//   docs/reference/alerts.md (marked block)          the alert table
//
//   node scripts/sync-alert-rules.js           # write
//   node scripts/sync-alert-rules.js --check   # fail if anything is stale (CI)
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { ALERTS, PATTERN_ALERTS, PLATFORM_ALERTS, NOTIFICATIONS, RUNBOOK_BASE, channelsFor, seconds } from '../backend/src/alerts/catalogue.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');
const stale = [];
const HEADER = 'Generated by scripts/sync-alert-rules.js from backend/src/alerts/catalogue.js. Do not edit.';

const yamlString = (s) => `'${String(s).replace(/'/g, "''")}'`;
const pascal = (name) => name.split(/[._-]/).map((p) => p[0].toUpperCase() + p.slice(1)).join('');

// ------------------------------------------------------------- vmalert ----
function vmalertRules() {
  const rules = [];
  const all = { ...ALERTS, ...PATTERN_ALERTS };
  for (const [name, a] of Object.entries(all)) {
    const filter = a.logsql ?? `event:=${JSON.stringify(name)}`;
    rules.push(
      [
        `      - alert: ${name}`,
        `        expr: ${yamlString(`service.name:="secure-notes" ${filter} _time:${a.when.window} | stats count() as n | filter n:>=${a.when.count}`)}`,
        `        labels:`,
        `          severity: ${a.severity}`,
        `        annotations:`,
        `          title: ${yamlString(a.title)}`,
        `          action: ${yamlString(a.action)}`,
        `          rule: ${yamlString(`at least ${a.when.count} in ${a.when.window}`)}`,
        `          runbook: ${yamlString(`${RUNBOOK_BASE}#${name.replace(/\./g, '')}`)}`,
      ].join('\n'),
    );
  }
  return [
    `# ${HEADER}`,
    '# vmalert evaluates each rule every 15 s over the window written in the query',
    '# (_time:...), on the logs the OpenTelemetry Collector ships to VictoriaLogs.',
    'groups:',
    '  - name: secure-notes',
    '    type: vlogs',
    '    interval: 15s',
    '    rules:',
    ...rules,
    '',
  ].join('\n');
}

// ------------------------------------------------- CloudWatch (template) ----
function cloudFormationBlock() {
  const out = [`  # ---- BEGIN generated alarms: ${HEADER}`];
  const all = { ...ALERTS, ...PATTERN_ALERTS };
  for (const [name, a] of Object.entries(all)) {
    const id = pascal(name);
    const pattern = a.cloudwatch ?? `{ $.event = "${name}" }`;
    const topic = a.severity === 'critical' ? 'OpsAlertsTopic' : 'OpsChatTopic';
    const period = Math.min(seconds(a.when.window), 86400);
    out.push(
      `  ${id}Filter:`,
      `    Type: AWS::Logs::MetricFilter`,
      `    Condition: MakeLogs`,
      `    Properties:`,
      `      LogGroupName: !Ref AppLogGroup`,
      `      FilterPattern: ${yamlString(pattern)}`,
      `      MetricTransformations:`,
      `        - MetricNamespace: !Sub SecureNotes/\${AWS::StackName}`,
      `          MetricName: ${id}`,
      `          MetricValue: '1'`,
      `          DefaultValue: 0`,
      `  ${id}Alarm:`,
      `    Type: AWS::CloudWatch::Alarm`,
      `    Condition: MakeLogs`,
      `    DependsOn: ${id}Filter`,
      `    Properties:`,
      `      AlarmName: !Sub \${AWS::StackName}-${name}`,
      `      AlarmDescription: ${yamlString(`[${a.severity}] ${a.title}. ${a.action}`.slice(0, 1024))}`,
      `      Namespace: !Sub SecureNotes/\${AWS::StackName}`,
      `      MetricName: ${id}`,
      `      Statistic: Sum`,
      `      Period: ${period}`,
      `      EvaluationPeriods: 1`,
      `      Threshold: ${a.when.count}`,
      `      ComparisonOperator: GreaterThanOrEqualToThreshold`,
      `      TreatMissingData: notBreaching`,
      `      AlarmActions: [!Ref ${topic}]`,
      // Recovery is news, not a page: OK goes to chat only.
      `      OKActions: [!Ref OpsChatTopic]`,
    );
  }
  out.push('  # ---- END generated alarms');
  return out.join('\n');
}

// ------------------------------------------------------- Alertmanager ----
function alertmanagerRoutes() {
  const all = { ...ALERTS, ...PATTERN_ALERTS };
  return [
    `# ---- BEGIN generated routes: ${HEADER}`,
    '# One route per alert: the receiver follows the severity (critical pages,',
    '# the rest goes to chat) and repeat_interval is the catalogue\'s "repeat".',
    'route:',
    '  receiver: sns-chat',
    '  group_by: [alertname]',
    '  group_wait: 5s',
    '  group_interval: 1m',
    '  repeat_interval: 1h',
    '  routes:',
    ...Object.entries(all).flatMap(([name, a]) => [
      `    - matchers: ['alertname="${name}"']`,
      `      receiver: ${a.severity === 'critical' ? 'sns-alerts' : 'sns-chat'}`,
      `      repeat_interval: ${a.repeat}`,
    ]),
    '# ---- END generated routes',
  ].join('\n');
}

// ---------------------------------------------------------------- docs ----
function docsTable() {
  const row = (name, a, how) =>
    `| \`${name}\` | ${a.severity} | ${a.title} | ${a.source ?? 'the app'} | ${channelsFor(a).join(', ')} | ${how} | ${a.repeat} |`;
  const lines = [
    `<!-- BEGIN generated: ${HEADER} -->`,
    '| Event | Severity | Means | Raised by | Channels | Fires when | Re-notify at most every (local) |',
    '| --- | --- | --- | --- | --- | --- | --- |',
    ...Object.entries(PLATFORM_ALERTS).map(([n, a]) => row(n, a, 'each matching read')),
    ...Object.entries(ALERTS).map(([n, a]) => row(n, a, `${a.when.count} in ${a.when.window}`)),
    ...Object.entries(PATTERN_ALERTS).map(([n, a]) => row(n, a, `${a.when.count} in ${a.when.window}`)),
    ...Object.entries(NOTIFICATIONS).map(([n, a]) => row(n, { ...a, source: 'the app (direct publish)' }, 'when it happens')),
    '',
    '## What to do',
    '',
    ...[...Object.entries(PLATFORM_ALERTS), ...Object.entries(ALERTS), ...Object.entries(PATTERN_ALERTS)].flatMap(([n, a]) => [`### ${n}`, '', `*${a.title}.* ${a.action}`, '']),
    '### credential.rotated',
    '',
    '*Information only.* The app read a new version of a secret and carried on. If you did not expect a rotation, check the secret\'s rotation schedule and CloudTrail.',
    '',
    '### alerting.test',
    '',
    '*Information only.* Someone pressed "Send a test alert" on the dashboard (demo mode). It proves the topic, the subscriptions and the delivery work.',
    '',
    '<!-- END generated -->',
  ];
  return lines.join('\n');
}

function write(file, content) {
  const p = path.join(root, file);
  const before = existsSync(p) ? readFileSync(p, 'utf8') : undefined;
  if (before === content) return;
  if (check) stale.push(file);
  else writeFileSync(p, content);
}

function replaceBlock(file, begin, end, block) {
  const p = path.join(root, file);
  if (!existsSync(p)) {
    if (check) stale.push(`${file} (missing)`);
    return;
  }
  const s = readFileSync(p, 'utf8');
  const a = s.indexOf(begin);
  const b = s.indexOf(end, a);
  if (a < 0 || b < 0) {
    // Deleting the markers must not switch the check off.
    if (check) stale.push(`${file} (markers missing)`);
    else console.error(`warning: ${file} has no markers; nothing generated there`);
    return;
  }
  const lineEnd = s.indexOf('\n', b);
  write(file, s.slice(0, a) + block + s.slice(lineEnd < 0 ? s.length : lineEnd));
}

write('deploy/observability/vmalert-rules.yaml', vmalertRules());
replaceBlock('deploy/observability/alertmanager.yml', '# ---- BEGIN generated routes', '# ---- END generated routes', alertmanagerRoutes());
replaceBlock('infra/cloudformation.yaml', '  # ---- BEGIN generated alarms', '  # ---- END generated alarms', cloudFormationBlock());
replaceBlock('docs/reference/alerts.md', '<!-- BEGIN generated', '<!-- END generated -->', docsTable());

if (check) {
  if (stale.length) {
    console.error(`stale: ${stale.join(', ')}. Run: node scripts/sync-alert-rules.js`);
    process.exit(1);
  }
  console.log('alert rules, alarms and the alert table match the catalogue');
} else {
  console.log('alert rules, alarms and the alert table written from the catalogue');
}
